#ifndef LLVM_URCL_SUBTARGET_H
#define LLVM_URCL_SUBTARGET_H

#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#include "URCLFrameLowering.h"
#include "URCLISelLowering.h"
#include "URCLInstrInfo.h"
#include "URCLSelectionDAGInfo.h"
#include "MCTargetDesc/URCLMCTargetDesc.h"

#define GET_SUBTARGETINFO_HEADER
#include "URCLGenSubtargetInfo.inc"

namespace llvm {

/// A specific URCL target MCU.
class URCLSubtarget : public URCLGenSubtargetInfo {
public:
  //! Creates an URCL subtarget.
  //! \param TT  The target triple.
  //! \param CPU The CPU to target.
  //! \param FS  The feature string.
  //! \param TM  The target machine.
  URCLSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
               const URCLTargetMachine &TM);

  const URCLInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const URCLTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const URCLSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
  const URCLRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  /// Parses a subtarget feature string, setting appropriate options.
  /// \note Definition of function is auto generated by `tblgen`.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  URCLSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS,
                                                const TargetMachine &TM);

  // Subtarget feature getters.
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool GETTER() const { return ATTRIBUTE; }
#include "URCLGenSubtargetInfo.inc"

private:
  // Subtarget feature settings
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "URCLGenSubtargetInfo.inc"

  URCLInstrInfo InstrInfo;
  URCLFrameLowering FrameLowering;
  URCLTargetLowering TLInfo;
  URCLSelectionDAGInfo TSInfo;
};

} // end namespace llvm

#endif // LLVM_URCL_SUBTARGET_H
